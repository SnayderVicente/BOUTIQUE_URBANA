-- CATEGORIA
CREATE TABLE CATEGORIA (
    IDCAT INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 1 INCREMENT BY 1,
    NOMCAT VARCHAR2(60),
    CONSTRAINT CAT_PK PRIMARY KEY (IDCAT)
);

-- PRODUCTO
CREATE TABLE PRODUCTO (
    CODPROD CHAR(3) NOT NULL,
    NOMPRO VARCHAR2(50),
    IDCAT INT NOT NULL,
    PREPRO NUMBER(8, 2),
    STOCKPRO INT,
    ESTPRO CHAR(1),
    CONSTRAINT PRO_PK PRIMARY KEY (CODPROD)
);

-- PERSONA
CREATE TABLE PERSONA (
    IDPER INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 200 INCREMENT BY 1,
    DNIPER CHAR(8),
    NOMPER VARCHAR2(60),
    APEPER VARCHAR2(80),
    EMAPER VARCHAR2(80),
    CELPER CHAR(9),
    TIPPER CHAR(1),
    FECNACPER DATE,
    ESTPER CHAR(1) DEFAULT 'A',
    CONSTRAINT PER_PK PRIMARY KEY (IDPER)
);

-- VENTA
CREATE TABLE VENTA (
    IDVEN INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 1 INCREMENT BY 1,
    FECVEN DATE,
    IDCLI INT,
    IDVEND INT,
    TIPPGVEN CHAR(1),
    ESTVEN CHAR(1),
    CONSTRAINT VEN_PK PRIMARY KEY (IDVEN)
);

-- VENTA_DETALLE
CREATE TABLE VENTA_DETALLE (
    IDVENDET INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 1 INCREMENT BY 1,
    IDVEN INT NOT NULL,
    CODPROD CHAR(3) NOT NULL,
    CANVENDET INT,
    CONSTRAINT VENDET_PK PRIMARY KEY (IDVENDET)
);

-- RELACIONES

-- VENTA_DETALLE con VENTA
ALTER TABLE VENTA_DETALLE
ADD CONSTRAINT vendet_ven_FK FOREIGN KEY (IDVEN)
REFERENCES VENTA(IDVEN);

-- VENTA_DETALLE con PRODUCTO
ALTER TABLE VENTA_DETALLE
ADD CONSTRAINT vendet_pro_FK FOREIGN KEY (CODPROD)
REFERENCES PRODUCTO(CODPROD);

-- VENTA con PERSONA (IDCLI)
ALTER TABLE VENTA
ADD CONSTRAINT ven_cli_FK FOREIGN KEY (IDCLI)
REFERENCES PERSONA(IDPER);

-- VENTA con PERSONA (IDVEND)
ALTER TABLE VENTA
ADD CONSTRAINT ven_vend_FK FOREIGN KEY (IDVEND)
REFERENCES PERSONA(IDPER);

-- PRODUCTO con CATEGORIA
ALTER TABLE PRODUCTO
ADD CONSTRAINT pro_cat_FK FOREIGN KEY (IDCAT)
REFERENCES CATEGORIA(IDCAT);

